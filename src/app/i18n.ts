export function formatTime(t: string, lang: Lang) {
  const [h, m] = t.split(":").map(Number);
  const pm = h >= 12;
  const h12 = h % 12 || 12;
  const suffix = lang === "ar" ? (pm ? "م" : "ص") : pm ? "PM" : "AM";
  return `${h12}:${String(m).padStart(2, "0")} ${suffix}`;
}
